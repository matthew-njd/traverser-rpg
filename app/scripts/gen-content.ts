/**
 * API → embedded content bundle codegen (T4 §5.1).
 *
 * Fetches `GET /content/bundle` from a running API and writes
 * `src/content/embedded.generated.ts` — the copy that ships inside the APK so a fresh install with
 * the PC off is still a playable game.
 *
 *   npm run gen:content                        — against http://localhost:8080/api/v1
 *   npm run gen:content -- <base-url>          — against anything else, /api/v1 prefix included
 *
 * ↯ Generated from the **served payload**, not from the C# seed source. The embedded copy and the
 * fetched copy must be the same bytes for the same version, and the only way to be sure of that is
 * for one to be a recording of the other. Parsing `ContentSeed*.cs` would put a second transcription
 * of the content beside the one the seed tests already assert against the fixtures.
 *
 * Registers a guest to get a token, because the endpoint is authenticated (DECISIONS 2026-08-01) —
 * cheaper than a codegen-only auth bypass, which would be a hole in the surface for a build step.
 * The player id below is **fixed**, so re-running reuses the one profile rather than littering the
 * dev database with a new guest per regeneration (registration is idempotent on it, tech-02 §3).
 */
const GEN_PLAYER_ID = '00000000-0000-7000-8000-00000000c0de';

import fs from 'node:fs';
import path from 'node:path';

const baseUrl = (process.argv[2] ?? 'http://localhost:8080/api/v1').replace(/\/+$/, '');
const outPath = path.resolve(import.meta.dirname, '..', 'src', 'content', 'embedded.generated.ts');

async function main(): Promise<void> {
  const registration = await fetch(`${baseUrl}/players`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      player_id: GEN_PLAYER_ID,
      traverser_name: 'gen-content',
      timezone: 'UTC',
    }),
  });

  if (!registration.ok) {
    throw new Error(`registration failed: ${registration.status} ${await registration.text()}`);
  }

  const { token } = (await registration.json()) as { token: string };

  const response = await fetch(`${baseUrl}/content/bundle`, {
    headers: { authorization: `Bearer ${token}`, accept: 'application/json' },
  });

  if (!response.ok) {
    throw new Error(`bundle fetch failed: ${response.status} ${await response.text()}`);
  }

  const bundle = (await response.json()) as { content_version: number };

  const banner =
    `// GENERATED by scripts/gen-content.ts from GET /content/bundle — do not edit.\n` +
    `// Regenerate with \`npm run gen:content\` after any content seed change + migration.\n` +
    `// content_version ${bundle.content_version}.\n\n`;

  // Pretty-printed rather than minified: this file is reviewed as a diff when content changes, and
  // a one-line payload makes "the Harpy's Power moved by 5" indistinguishable from a reseed.
  const source =
    `${banner}/** The bundle as served at build time (T4 §5.1). Superseded by any newer fetch. */\n` +
    `export const EMBEDDED_BUNDLE = ${JSON.stringify(bundle, null, 2)} as const;\n`;

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, source);

  console.log(`gen-content: content_version ${bundle.content_version} written to ${outPath}`);
}

await main();
